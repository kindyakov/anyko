// Сроки повтора команды (ADR 0009, data-and-jobs.md). Результат хранится сутки: повтор позже
// считается новой командой. Захват без результата (процесс упал между выполнением и записью)
// перехватывается через пять минут: иначе ключ зависал бы навсегда.
export const RESULT_RETENTION_MS = 24 * 60 * 60 * 1000;
export const CAPTURE_LEASE_MS = 5 * 60 * 1000;

// Момент через заданное число миллисекунд: часы передаёт вызывающий, здесь только арифметика.
export function afterMs(instant: Date, ms: number): Date {
  return new Date(instant.getTime() + ms);
}
