const directAbsence: ReadonlyMap<string, RegExp> = new Map([
  [
    'businessDebts',
    /^(?:у меня\s+)?предпринимательск\p{L}*\s+(?:обязательств|долг|задолженност)\p{L}*\s*[:—-]?\s*(?:нет|отсутству\p{L}*)$/u,
  ],
  [
    'businessReceivables',
    /^(?:предпринимательск\p{L}*\s+(?:требовани|должник|дебиторск\p{L}*\s+задолженност)\p{L}*|(?:дебиторск\p{L}*\s+задолженност|должник)\p{L}*\s+по предпринимательской деятельности)\s*[:—-]?\s*(?:нет|отсутству\p{L}*)$/u,
  ],
  [
    'businessPayments',
    /^(?:предпринимательск\p{L}*\s+(?:обязательн\p{L}*\s+)?платеж\p{L}*|(?:обязательн\p{L}*\s+)?платеж\p{L}*\s+по предпринимательской деятельности)\s*[:—-]?\s*(?:нет|отсутству\p{L}*)$/u,
  ],
  [
    'businessRefunds',
    /^(?=предпринимательск|.* по предпринимательской деятельности)(?:предпринимательск\p{L}*\s+)?(?:платеж|сумм)\p{L}*\s+(?:к\s+)?(?:возврат|зач[её]т)\p{L}*(?:\s+(?:или|и)\s+(?:возврат|зач[её]т)\p{L}*)?(?:\s+по предпринимательской деятельности)?\s*[:—-]?\s*(?:нет|отсутству\p{L}*)$/u,
  ],
]);

export function businessAbsenceRule(field: string) {
  return directAbsence.get(field);
}

export function businessAbsenceInstructions(keys: ReadonlySet<string>) {
  const fields = [...directAbsence.keys()].filter((field) => keys.has(field));
  return (
    fields.length > 0 &&
    `Для ${fields.join(', ')} верни value=[], если документ прямо подтверждает отсутствие записей данного вида либо одновременно сообщает, что заявитель не занимался предпринимательской деятельностью и не имел статуса ИП. Такое утверждение — прямое сведение: если схема содержит origin, укажи origin: document. Во втором случае приведи одну дословную цитату, содержащую обе части. Одной части или отсутствия упоминания недостаточно.`
  );
}
