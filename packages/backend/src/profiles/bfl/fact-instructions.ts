import {
  type FieldDefinition,
  isCalendarDateField,
  isRublesColumn,
} from './fields';

export function factInstructions(fields: readonly FieldDefinition[]) {
  const keys = new Set(fields.map(({ key }) => key));
  const hasInn =
    keys.has('inn') ||
    fields.some(({ columns }) => columns.some(({ key }) => key === 'inn'));
  return [
    fields.some(({ kind }) => kind === 'rows') &&
      'Пустой массив допустим при явно подтверждённом отсутствии строк. Неизвестное поле пропусти целиком.',
    (keys.has('previousNames') || fields.some(({ multiline }) => multiline)) &&
      'Явное отрицание в источнике считается сведением: извлеки его с дословной цитатой. Например, «судимости нет» из анкеты относится к criminalCasesDetails, если поле доступно. Отсутствие упоминания ничего не подтверждает.',
    keys.has('previousNames') &&
      'Для previousNames извлеки указанные прежние ФИО. Если источник прямо сообщает, что ФИО не менялись, верни значение «не менялись» и процитируй это утверждение.',
    hasInn &&
      'ИНН в value или в ячейке inn — строка из цифр без подписи реквизита, с ведущими нулями. У физлица 12 цифр, у организации 10. Номер должен полностью присутствовать в цитате.',
    keys.has('snils') &&
      'СНИЛС в value — строка из 11 цифр с ведущими нулями, допустимы пробелы и дефисы между цифрами. Подпись реквизита оставь только в цитате. При неполном номере не восстанавливай цифры.',
    (keys.has('inn') ||
      keys.has('snils') ||
      fields.some(
        ({ key }) =>
          isCalendarDateField(key) ||
          key === 'cashOnHand' ||
          key === 'debtTotal',
      )) &&
      'Для автоматического заполнения ИНН и СНИЛС должника, дат и сумм в отдельных полях нужна текстовая цитата (imagePath=null), в которой прямо указан полный номер, дата или сумма.',
    keys.has('citizenship') &&
      'Гражданство России для автоматического заполнения подтверждай текстом российского паспорта: процитируй название паспорта или заголовок «Российская Федерация» вместе с паспортными полями фамилии, имени и места рождения.',
    fields.some(({ key, columns }) =>
      columns.some(
        ({ key: column }) =>
          isRublesColumn(key, column) ||
          column === 'inn' ||
          (key === 'valuables' && column === 'amount'),
      ),
    ) &&
      'Для автоматического заполнения сумм и ИНН в обычной таблице процитируй значение и опознавательные колонки (например, название и основание) в одной строке текстовой цитаты (imagePath=null). Для банковских обязательств и занятости следуй их отдельным правилам. В valuables сохраняй валюту источника.',
  ]
    .filter(Boolean)
    .join(' ');
}
